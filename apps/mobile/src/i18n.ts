export const i18nReady = (async () => {
  let savedLanguage: string | null = null;

  try {
    savedLanguage = await SecureStore.getItemAsync(LANGUAGE_STORAGE_KEY);
  } catch {
  }

  await i18n.use(initReactI18next).init({
    resources,
    lng: savedLanguage === "ur" ? "ur" : "en",
    fallbackLng: "en",
    interpolation: { escapeValue: false },
    returnNull: false,
  });
})();

export async function changeAppLanguage(language: AppLanguage) {
  await i18nReady;
  await i18n.changeLanguage(language);

  try {
    await SecureStore.setItemAsync(LANGUAGE_STORAGE_KEY, language);
  } catch {
  }
}

export default i18n;