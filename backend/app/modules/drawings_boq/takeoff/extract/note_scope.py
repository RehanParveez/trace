def scope_of(code: str | None) -> str:
  return SCOPE.get(code or "", ROW)

def note_scope(n: dict) -> str:
  return n.get("scope") or scope_of(n.get("code"))

def has_warning(notes) -> bool:
  return any(isinstance(n, dict) and n.get("severity") == "warning" for n in notes or [])

def status_of(notes) -> str:
  sev = {n.get("severity") for n in notes or [] if isinstance(n, dict) and (n.get("severity") == "error" or note_scope(n) == ROW)}
  return "INVALID" if "error" in sev else "WARNING" if "warning" in sev else "VALID"

def split(notes) -> dict:
  out: dict = {ROW: [], SHEET: [], DRAWING: []}
  for n in notes or []:
    if isinstance(n, dict):
      out[note_scope(n)].append(n)
  return out
